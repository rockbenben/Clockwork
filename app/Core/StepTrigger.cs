namespace Clockwork.Core;

/// <summary>这一步是谁触发的。决定两件事：成功要不要弹回执、要不要防连点。</summary>
//
// 合成一个枚举而不是两个 bool：它们不是两个独立开关，是同一个事实（谁按的）的两个后果。
// 分开写迟早会配出「安静但仍然防连点」这种没人想要的组合，而那个组合恰恰无声——
// 手势被闸拦下时什么都不说，表现就是「我画了，没反应」。
public enum StepTrigger
{
    /// <summary>界面上的「运行」按钮、面板格子。要回执（那是它唯一的结果），也要防连点。</summary>
    Button,

    /// <summary>鼠标手势。成功安静（动作本身就是回答），失败照报；不防连点——
    /// 画两次就是故意要跑两次（↖ 切换置顶：钉住、再放开）。</summary>
    Gesture,
}
